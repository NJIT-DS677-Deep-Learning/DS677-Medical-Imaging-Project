'''
Now, we will extract one non-lesion sample from each original image

Note that we will have fewer of these because some images have multiple lesions and because we want to ensure we have sufficient non-blank space
We also have selection criteria outlined in the code to ensure we don't include more than a threshold proportion of blank space or the lesion
'''

def get_context(
    image_path,
    bounding_boxes,
    box_adj = 50,
    intensity_threshold = -500,
    min_tissue_fraction = 0.9,
    min_size = 100,
    max_size = 125,
    max_attempts = 5000
):

  # Load original image
  with Image.open(image_path) as img:
    image = np.array(img)

  height, width = image.shape[:2]

  # Convert image to grayscale for tissue detection (tissue is bright, blank space is dark)
  if image.ndim == 3:
    grayscale = np.mean(image, axis = 2)
  else:
    grayscale = image


  # Correct the 16-bit DeepLesion PNG intensity offset
  # Documented in original dataset, and especially important for lung CT scans where there is naturally a lot of air
  # We adjust for the purpose of filtering, and still export the original image section as the crop
  # We will adjust all of the candidates for both lesions and non-lesion extracts after padding
  grayscale = grayscale.astype(np.float32) - 32768.0


  # Use mask to only keep crops with specified fraction of Hounsfield Units above threshold value
  # Threshold value of -500 removes air (-1000 HU and blank space)
  tissue_mask = grayscale > intensity_threshold

  # Store bounding boxes which we will exclude from candidates
  exclusion_boxes = []

  for bounding_box in bounding_boxes:
    x_min, y_min, x_max, y_max = map(
            float, bounding_box.split(",")
        )

    # Expand bounding box by additional pixels
    x_min = int(np.floor(x_min - box_adj))
    y_min = int(np.floor(y_min - box_adj))
    x_max = int(np.ceil(x_max + box_adj))
    y_max = int(np.ceil(y_max + box_adj))

    # Clip coordinates to image boundaries
    x_min = max(0, x_min)
    y_min = max(0, y_min)
    x_max = min(width, x_max)
    y_max = min(height, y_max)

    exclusion_boxes.append(
        (x_min, y_min, x_max, y_max)
    )

  # Randomly search for a valid candidate
  for _ in range(max_attempts):

    # Choose crop dimensions within predefined boundaries
    crop_height = np.random.randint(
        min_size, min(max_size, height) + 1
    )

    crop_width = np.random.randint(
        min_size, min(max_size, width) + 1
    )

    # Restrict candidate selection to the central image region
    min_x = int(width * 0.25)
    max_x = int(width * 0.75) - crop_width

    min_y = int(height * 0.25)
    max_y = int(height * 0.75) - crop_height

    # Ensure crop fits within the selection region
    if max_x < min_x or max_y < min_y:
      continue

    # Randomly select crop coordinates
    x_min = np.random.randint(min_x, max_x + 1)
    y_min = np.random.randint(min_y, max_y + 1)

    # Calculate bottom-right coordinates of candidate crop
    x_max = x_min + crop_width
    y_max = y_min + crop_height

    # Check if crop passes through bounded box we need to exclude
    # Evaluates horizontal and vertical directions
    # If all four conditions are true, the rectangles overlap
    # If any condition is false, the rectangles do not overlap
    overlaps_lesion = any(
          x_min < bx_max and x_max > bx_min
          and y_min < by_max and y_max > by_min
          for bx_min, by_min, bx_max, by_max in exclusion_boxes
      )

    if overlaps_lesion:
      continue

    # Now test tissue presence via brightness
    candidate_mask = tissue_mask[y_min : y_max, x_min : x_max]

    # Calculate proportion of image considered tissue based on average brightness
    tissue_fraction = np.mean(candidate_mask)

    # If too much background (too much blank space), reject
    if tissue_fraction < min_tissue_fraction:
      continue

    # Otherwise, extract valid crop
    context = image[y_min : y_max, x_min : x_max]

    return context, (x_min, y_min, x_max, y_max), tissue_fraction

  # If cannot find crop for the image after maximum attempts, raise error
  raise ValueError(
      "Could not find valid context crop for this image after maximum attempts."
  )

