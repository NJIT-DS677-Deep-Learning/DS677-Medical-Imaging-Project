import numpy as np
from PIL import Image


def get_lesion(image_path, bounding_box, box_adj = 50):
  # Get original pixel values from each image and store as array
  with Image.open(image_path) as img:
    image = np.array(img)

  # Read in coordinates of each corner of bounding box
  x_min, y_min, x_max, y_max = map(
      float, (bounding_box.split(","))
      )

  # Expand bounding box by aditional pixels in every direction
  x_min = int(np.floor(x_min - box_adj))
  y_min = int(np.floor(y_min - box_adj))
  x_max = int(np.ceil(x_max + box_adj))
  y_max = int(np.ceil(y_max + box_adj))

  # Get image dimensions
  height, width = image.shape[:2]

  # Clip coordinates to image boundaries to make sure the box location is valid
  x_min = max(0, x_min)
  y_min = max(0, y_min)
  x_max = min(width, x_max)
  y_max = min(height, y_max)

  # Crop image based on the four coordinates above so we can extract the lesion and some surrounding context
  lesion = image[y_min : y_max, x_min : x_max]

  # Ensure bounding box is valid
  if lesion.size == 0:
    raise ValueError('Invalid or empty lesion bounding box')

  return lesion

