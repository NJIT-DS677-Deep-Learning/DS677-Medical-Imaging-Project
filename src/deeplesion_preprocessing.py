# Outline target image size so all images are padded to be the same
# We will pad with air (Hounsfield Unit = -1000)
target_size = 140

# Reset dataframe index for unique filenames
df_export = df_filtered.reset_index(drop=True)


# Iterate through df_filtered to put all images in folder

hpc_records = []
failed = []

for idx, row in df_filtered.reset_index(drop = True).iterrows():

  # Identify image path
  source_path = Path(row["Image_path"])

  try:

    # Check that path exists
    if not source_path.exists():
      print(f"Missing image: {source_path}")
      continue

    # Load raw image
    raw = np.array(Image.open(source_path))

    # Check if image is in grayscale (2 channels)
    if raw.ndim !=2:
      raise ValueError(f"Expected grayscale image, got {raw.shape}")

    # Convert pixel values to hounsfield units as to make patterns more visible
    hu = raw.astype(np.float32) - 32768.0

    # Extract current height and width of image so we know how to pad
    original_height, original_width = hu.shape

    # Make sure image fits into target size
    if original_height > target_size or original_width > target_size:
      raise ValueError(f"Image exceeds size target: {hu.shape}")

    # Calculate symmetric padding to preserve original pattern of lesion / tissue
    pad_height = target_size - original_height
    pad_width = target_size - original_width

    # Apply height padding equally to top and bottom
    top = pad_height // 2
    bottom = pad_height - top

    # Same for left and right
    left = pad_width // 2
    right = pad_width - left

    # Apply padding using -1000 Hounsfield Units (air)
    padded_hu = np.pad(
        hu,
        ((top, bottom), (left, right)),
        mode = "constant",
        constant_values = -1000
    )


    # Normalize Hounsfield values to be between 0 and 1 for easier interpretation
    # This makes air 0
    # Change Hounsfield unit of -1000 to 1000 then normalize
    normalized_image = np.clip(padded_hu, -1000, 1000)
    normalized_image = (normalized_image + 1000) / 2000


    # Store array values as float
    normalized_image = normalized_image.astype(np.float32)

    # Save processed image
    # Create filename
    crop_type = row["Crop_type"].lower()

    new_filename = (
        f"{idx:07d}_{crop_type}.npy"
    )

    # Set up subset of image dir
    destination_path = images_dir / new_filename

    # Save new array to path
    np.save(destination_path, normalized_image)

    # Save metadata
    hpc_records.append({
        "Image_name": new_filename,
        "Image_path": f"images/{new_filename}",
        "Label": int(row["Label"]),
        "Crop_type": row["Crop_type"],
        "Patient_ID": row["Patient_ID"],
        "Original_file": row["Original_file"],
        "Original_height": original_height,
        "Original_width": original_width,
        "Height": target_size,
        "Width": target_size,
        "Area": target_size * target_size,
        "Pixel_format": "float32_normalized_HU",
        "HU_window": "-1000 to 1000"
    })

  except Exception as e:
    failed.append({
        "Index": idx,
        "Source path": str(source_path),
        "Error": str(e)
    })

 # Progress reporting
    if (idx + 1) % 50 == 0 or (idx + 1) == len(df_export):
        print(f"Processed {idx + 1}/{len(df_export)} images")


# Create dfs with results
df_hpc = pd.DataFrame(hpc_records)
df_failed = pd.DataFrame(failed)

# Save metadata to directory
df_hpc.to_csv(hpc_dir / "metadata.csv", index = False)

# Save failed image log
df_failed.to_csv(hpc_dir / "failed_images.csv", index = False)

# Evaluate results
print(f"Images successfully copied: {len(df_hpc)}")
print(f"Destination: {images_dir}")
print(f"Metadata saved: {hpc_dir / 'metadata.csv'}")
