# Import packages
import numpy as np
import pandas as pd
import torch

from pathlib import Path
from torch.utils.data import Dataset

'''
Set up DeepLesionDataset class
'''

class DeepLesionDataset(Dataset):

  # Set up init function to read in metadata file and perform quality checks

  def __init__(self, root_dir, metadata_file = "metadata.csv"):

    # Find directory containing dataset
    self.root_dir = Path(root_dir)

    # Find directory containing metadata file
    self.metadata_path = self.root_dir / metadata_file

    # Check to make sure metadata file exists
    if not self.metadata_path.exists():
      raise FileNotFoundError(
          f"Metadata file not found: {self.metadata_path}"
      )

    # Read metadata file in
    self.metadata = pd.read_csv(self.metadata_path)

    # Make sure required metadata columns exist
    required = ["Image_path", "Label", "Patient_ID"]

    missing = [
        col for col in required if col not in self.metadata.columns
    ]

    if missing:
      raise ValueError(
          f"Missing required metadata columns: {missing}"
    )

    # Make sure labels are only 0 or 1
    if not self.metadata["Label"].isin([0, 1]).all():
      raise ValueError("Labels must be 0 or 1")

  # Set up function to find the length of the metadta file

  def __len__(self):
    return len(self.metadata)

  # Set up function to read data in for each image and set up as PyTorch tensor

  def __getitem__(self, idx):

    # Get metadata row for the image
    row = self.metadata.iloc[idx]

    # Construct full filepath
    image_path = self.root_dir / row["Image_path"]

    # Check that image file exists
    if not image_path.exists():
      raise FileNotFoundError(
          f"Image not found: {image_path}"
      )

    # Load the image we already preprocessed into a numpy array
    image = np.load(image_path)

    # Confirm image dimensions are the 140 * 140 we padded to
    if image.shape != (140, 140):
      raise ValueError(
          f"Unexpected image shape {image.shape}: {image_path}"
      )

    # Convert image into PyTorch tensor
    # Need to add channel dimension, currently just have height and width
    # Image is grayscale, for there is only one channel
    # Add channel to front with unsqueeze
    image = torch.from_numpy(
        image.astype(np.float32, copy = False)
    ).unsqueeze(0)

    # Also convert the label for this particular row as a tensor
    label = torch.tensor(
        int(row["Label"]),
        dtype = torch.long
    )

    # Return image and label
    return image, label